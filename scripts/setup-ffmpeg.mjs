// @ffmpeg/ffmpeg 의 ESM 워커 소스를 의존성까지 한 파일로 인라인해 public/ffmpeg/worker.js 로 생성한다.
//
// 배경:
// - @ffmpeg 워커는 코어를 `import(coreURL)`(coreURL=blob)로 로드한다.
// - Next(webpack)가 워커를 번들하면 이 동적 import 를 재작성해 런타임에 blob 코어를
//   "Cannot find module 'blob:...'" 로 못 찾는다. (@ffmpeg 가 배포하는 UMD 워커 번들
//   814.ffmpeg.js 역시 자체 webpack 빌드로 이미 깨져 있어 그대로 쓰면 동일 증상.)
// - 해결: ESM 워커 *소스*(native `import()`)를 const.js/errors.js 까지 인라인해 단일
//   정적 모듈로 만들고 public 에 둔다. 정적 파일은 어떤 번들러도 거치지 않으므로
//   import 가 네이티브로 동작한다. 이 파일을 classWorkerURL 로 넘긴다.
//
// 실패해도 빌드를 막지 않도록 항상 정상 종료한다(저장소에 커밋된 사본을 그대로 사용).

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

try {
  const esmDir = join(root, "node_modules", "@ffmpeg", "ffmpeg", "dist", "esm");

  const constSrc = readFileSync(join(esmDir, "const.js"), "utf8")
    .replace(/^export\s+/gm, "");
  const errorsSrc = readFileSync(join(esmDir, "errors.js"), "utf8")
    .replace(/^export\s+/gm, "");
  const workerSrc = readFileSync(join(esmDir, "worker.js"), "utf8")
    // 인라인하므로 const.js / errors.js import 라인 제거
    .replace(/^import\s+\{[\s\S]*?\}\s+from\s+["']\.\/const\.js["'];?\s*$/m, "")
    .replace(/^import\s+\{[\s\S]*?\}\s+from\s+["']\.\/errors\.js["'];?\s*$/m, "");

  const out =
    "// AUTO-GENERATED by scripts/setup-ffmpeg.mjs — do not edit by hand.\n" +
    "// Self-contained native-ESM @ffmpeg worker (avoids webpack dynamic-import breakage).\n\n" +
    constSrc + "\n" + errorsSrc + "\n" + workerSrc;

  const outDir = join(root, "public", "ffmpeg");
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, "worker.js"), out);
  console.log("[setup-ffmpeg] generated public/ffmpeg/worker.js (inlined native ESM worker)");
} catch (error) {
  console.warn("[setup-ffmpeg] skipped:", error?.message ?? error);
}
